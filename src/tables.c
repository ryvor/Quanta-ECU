// Simple bilinear lookup
float table_lookup(const float table[RPM_TABLE_SIZE][MAP_TABLE_SIZE], float rpm, float kpa) {
    float rpm_step = 7000.0f / (RPM_TABLE_SIZE - 1);
    float map_step = 100.0f / (MAP_TABLE_SIZE - 1);
    int ri = rpm / rpm_step;
    int mi = kpa / map_step;
    if (ri < 0) ri = 0; if (ri >= RPM_TABLE_SIZE-1) ri = RPM_TABLE_SIZE-2;
    if (mi < 0) mi = 0; if (mi >= MAP_TABLE_SIZE-1) mi = MAP_TABLE_SIZE-2;
    float rf = (rpm - ri*rpm_step)/rpm_step;
    float mf = (kpa - mi*map_step)/map_step;
    float v00 = table[ri][mi];
    float v10 = table[ri+1][mi];
    float v01 = table[ri][mi+1];
    float v11 = table[ri+1][mi+1];
    float v0 = v00 + (v01 - v00)*mf;
    float v1 = v10 + (v11 - v10)*mf;
    return v0 + (v1 - v0)*rf;
}
